async (page) => {
  const { origin, hostname } = await page.evaluate(() => ({ origin: location.origin, hostname: location.hostname }))
  if (!["localhost", "127.0.0.1"].includes(hostname)) {
    throw new Error("Practice audit only runs against a local demo workspace.")
  }
  const checks = []
  const failures = []
  const onPageError = error => failures.push(error.message)
  page.on("pageerror", onPageError)
  const assert = (condition, message) => { if (!condition) throw new Error(message) }
  const visit = async route => {
    await page.goto(`${origin}/${route}`)
    await page.getByRole("main").waitFor()
    assert(!page.url().includes("/login"), "Sign in to the local demo before this audit.")
  }
  const screenshot = async name => {
    await page.screenshot({ path: `output/playwright/${name}.png`, fullPage: true })
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)
    assert(!overflow, `${name} has horizontal page overflow`)
  }
  try {
    await page.setViewportSize({ width: 1440, height: 900 })
    await visit("practice")
    await page.getByRole("button", { name: /^Algorithms Practice Algorithms/ }).click()
    await page.getByRole("heading", { name: "Algorithms Practice", exact: true }).waitFor()
    await page.getByLabel("Practice options", { exact: true }).click()
    await page.getByRole("button", { name: "Clear draft", exact: true }).click()
    await page.getByLabel("Practice options", { exact: true }).click()
    await page.getByRole("button", { name: "O(log n)", exact: true }).click()
    assert(await page.getByRole("progressbar", { name: "Questions answered" }).getAttribute("aria-valuenow") === "17", "Quiz progress did not update")
    await page.getByRole("button", { name: "Next question", exact: true }).click()
    await page.getByRole("heading", { name: "Which sorting algorithm has the best average-case time complexity?" }).waitFor()
    await page.getByRole("button", { name: "Previous question", exact: true }).click()
    assert(await page.getByRole("button", { name: /^O\(log n\)/ }).getAttribute("aria-pressed") === "true", "Quiz answer was lost on navigation")
    await page.getByRole("button", { name: "Submit", exact: true }).click()
    await page.getByText("5 missed", { exact: true }).waitFor()
    await page.getByText("Review plan", { exact: true }).click()
    await page.getByText(/^Weak topics/).waitFor()
    await page.getByText("Review plan", { exact: true }).click()
    await screenshot("practice-result-desktop")
    await page.getByRole("button", { name: "Retry missed", exact: true }).click()
    assert(await page.getByRole("button", { name: "O(log n)", exact: true }).count() === 0, "Retry still includes the correctly answered question")
    checks.push("Quiz: answer, progress, next/previous, submit, collapsed review plan, retry missed")

    await visit("games")
    await page.locator(".game-choices button").first().waitFor()
    await page.getByText("Setup", { exact: true }).click()
    await page.getByRole("button", { name: "1:30", exact: true }).click()
    await page.getByText("Setup", { exact: true }).click()
    await page.locator(".game-choices button").first().click()
    assert(await page.locator(".game-choices button:disabled").count() > 0, "Sprint choices were not locked after answering")
    await screenshot("sprint-feedback-desktop")
    await page.getByRole("button", { name: "Restart", exact: true }).click()
    assert(await page.locator(".game-choices button:disabled").count() === 0, "Sprint restart did not unlock choices")
    checks.push("Sprint: 90-second setup label, answer lock, feedback, restart")

    await visit("live")
    await page.getByRole("button", { name: "Streak", exact: true }).click()
    assert(await page.getByRole("button", { name: "Streak", exact: true }).getAttribute("aria-pressed") === "true", "Live mode did not change")
    await page.getByText("Correct answers build a multiplier up to ×3.", { exact: true }).waitFor()
    await screenshot("live-modes-desktop")
    await page.setViewportSize({ width: 390, height: 844 })
    await screenshot("live-modes-phone")
    await page.getByRole("button", { name: "Host game", exact: true }).click()
    await page.getByTestId("live-join-code").waitFor()
    assert((await page.getByTestId("live-join-code").innerText()).length === 6, "Live lobby has no join code")
    assert(await page.getByRole("button", { name: "Start quiz", exact: true }).isDisabled(), "Empty live lobby should not start")
    await page.getByRole("button", { name: "End", exact: true }).click()
    await page.getByText("Saved results", { exact: true }).waitFor()
    await page.getByRole("button", { name: "Leave screen", exact: true }).click()
    await page.getByRole("button", { name: "Host game", exact: true }).waitFor()
    checks.push("Live: mode tiles, selected rules, phone layout, host lobby, empty-lobby guard, end, leave")

    await visit("calendar")
    const calendar = page.getByRole("region", { name: "Calendar", exact: true })
    const month = calendar.getByRole("heading", { level: 3 }).first()
    await month.waitFor()
    const initialMonth = await month.innerText()
    await page.getByRole("button", { name: "Next month", exact: true }).click()
    assert(await month.innerText() !== initialMonth, "Month navigation did not move")
    await page.getByRole("button", { name: "Previous month", exact: true }).click()
    assert(await month.innerText() === initialMonth, "Month navigation did not return")
    await page.getByRole("button", { name: "Next year", exact: true }).click()
    assert(await month.innerText() !== initialMonth, "Year navigation did not move")
    await page.getByRole("button", { name: "Previous year", exact: true }).click()
    assert(await month.innerText() === initialMonth, "Year navigation did not return")
    await page.getByRole("button", { name: "week", exact: true }).click()
    await page.getByRole("button", { name: "Next week", exact: true }).click()
    await page.getByRole("button", { name: "Previous week", exact: true }).click()
    await page.getByRole("button", { name: "month", exact: true }).click()
    await page.getByText("Filters", { exact: true }).click()
    const study = page.getByRole("button", { name: "Study", exact: true })
    const visibleBefore = await study.getAttribute("aria-pressed")
    await study.click()
    assert(await study.getAttribute("aria-pressed") !== visibleBefore, "Calendar category filter did not toggle")
    await study.click()
    await page.getByText("Filters", { exact: true }).click()
    await page.getByRole("button", { name: "Calendar connections", exact: true }).click()
    await page.getByRole("dialog", { name: "Calendar accounts" }).waitFor()
    await page.getByLabel("How calendar connections work").click()
    await page.getByText(/Changes save directly to the selected calendar/).waitFor()
    await screenshot("calendar-connections-phone")
    await page.getByRole("button", { name: "Close calendar connections", exact: true }).click()

    const eventName = `Playwright practice audit ${Date.now()}`
    await page.getByRole("button", { name: "Add", exact: true }).click()
    await page.getByRole("textbox", { name: "Event title", exact: true }).fill(eventName)
    await page.getByText("More details", { exact: true }).click()
    await page.getByRole("textbox", { name: "Notes", exact: true }).fill("Local browser regression check")
    await screenshot("calendar-event-phone")
    await page.getByRole("button", { name: "Save", exact: true }).click()
    const event = page.getByRole("list", { name: "Selected day events" }).getByRole("button", { name: new RegExp(eventName) })
    await event.waitFor()
    await event.click()
    assert(await page.getByRole("textbox", { name: "Notes", exact: true }).inputValue() === "Local browser regression check", "Calendar notes were not saved")
    await page.getByRole("button", { name: "Delete event", exact: true }).click()
    await page.getByRole("dialog", { name: "Edit event" }).waitFor({ state: "hidden" })
    await event.waitFor({ state: "hidden" })
    checks.push("Calendar: month/year/week navigation, category filter, connection help, create/open/delete event with notes")
    assert(failures.length === 0, `Uncaught browser errors: ${failures.join("; ")}`)
    return { passed: checks, screenshots: "output/playwright", limitations: ["Live multiplayer and external calendar authorization require separate accounts or provider credentials.", "Quiz submission and finished empty live session remain in the local demo history."] }
  } finally {
    page.off("pageerror", onPageError)
  }
}
